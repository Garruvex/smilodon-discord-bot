function englishOrdinal(age: number): string {
  const lastTwo = age % 100;
  const suffix = lastTwo >= 11 && lastTwo <= 13 ? "th" : ({ 1: "st", 2: "nd", 3: "rd" } as Record<number, string>)[age % 10] ?? "th";
  return `${age}${suffix}`;
}

